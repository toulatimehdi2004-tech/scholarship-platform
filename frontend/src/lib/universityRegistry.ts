export interface VerificationResult {
  isVerified: boolean;
  university?: AccreditedUniversity;
  matchedBy?: 'primary_email' | 'secondary_gmail' | 'domain';
  error?: string;
}

/**
 * Checks if an email address belongs to an accredited admissions office or verified Gmail desk.
 */
export function verifyUniversityEmail(
  rawEmail: string,
  targetUniId?: number | null
): VerificationResult {
  const email = (rawEmail || '').trim().toLowerCase();
  if (!email || !email.includes('@')) {
    return {
      isVerified: false,
      error: 'Format d\'email invalide. Veuillez entrer une adresse email valide.',
    };
  }

  // If specific university selected, verify against that university
  if (targetUniId) {
    const uni = ACCREDITED_UNIVERSITIES.find((u) => u.id === targetUniId);
    if (!uni) {
      return { isVerified: false, error: 'Université sélectionnée introuvable dans le registre.' };
    }

    if (uni.secondary_email && email === uni.secondary_email.toLowerCase()) {
      return { isVerified: true, university: uni, matchedBy: 'secondary_gmail' };
    }
    if (uni.admissions_email && email === uni.admissions_email.toLowerCase()) {
      return { isVerified: true, university: uni, matchedBy: 'primary_email' };
    }
    if (uni.official_domain && email.endsWith('@' + uni.official_domain.toLowerCase())) {
      return { isVerified: true, university: uni, matchedBy: 'domain' };
    }

    return {
      isVerified: false,
      university: uni,
      error: `Accès refusé. L'email ne correspond pas au bureau des admissions de ${uni.name} (${uni.admissions_email} ou ${uni.secondary_email}).`,
    };
  }

  // Otherwise search across all 102 accredited universities
  for (const uni of ACCREDITED_UNIVERSITIES) {
    if (uni.secondary_email && email === uni.secondary_email.toLowerCase()) {
      return { isVerified: true, university: uni, matchedBy: 'secondary_gmail' };
    }
    if (uni.admissions_email && email === uni.admissions_email.toLowerCase()) {
      return { isVerified: true, university: uni, matchedBy: 'primary_email' };
    }
    if (uni.official_domain && email.endsWith('@' + uni.official_domain.toLowerCase())) {
      return { isVerified: true, university: uni, matchedBy: 'domain' };
    }
  }

  return {
    isVerified: false,
    error: 'Accès refusé : Cette adresse email n\'est pas reconnue dans le registre officiel des universités partenaires. Seuls les officiers d\'admissions accrédités sont autorisés.',
  };
}

/**
 * Find an accredited university by numeric ID or by name
 */
export function findAccreditedUniversity(
  idOrName: number | string | undefined | null
): AccreditedUniversity | undefined {
  if (!idOrName) return undefined;
  if (typeof idOrName === 'number') {
    return ACCREDITED_UNIVERSITIES.find((u) => u.id === idOrName);
  }
  const clean = String(idOrName).toLowerCase().trim();
  const num = Number(clean);
  if (!isNaN(num) && num > 0) {
    const byId = ACCREDITED_UNIVERSITIES.find((u) => u.id === num);
    if (byId) return byId;
  }
  return ACCREDITED_UNIVERSITIES.find(
    (u) =>
      u.name.toLowerCase() === clean ||
      clean.includes(u.name.toLowerCase()) ||
      u.name.toLowerCase().includes(clean)
  );
}

